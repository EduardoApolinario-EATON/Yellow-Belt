SELECT '1.SYNCHRO' "LOCAL",
       D.NAME "SOURCE",
       COUNT(A.TRX_NUMBER) NF_DELIVERY,
       'AFT' ORDEM,
       'Aguardar tempo das notas autorizarem na SEFAZ' "OBS"
  FROM APPS.XXRA_CUSTOMER_TRX_BR_V       A,
       APPS.XXCLL_F031_ELECTRONIC_TRX_ALL_BR_V B,
       APPS.XXRA_CUST_TRX_TYPES_BR_V     C,
       APPS.XXRA_BATCH_SOURCES_BR_V      D,
       APPS.XXETN_RA_CUSTOMERS E,
       APPS.FND_USER_VIEW F,
       APPS.XXETN_RA_CUSTOMERS ra
where A.CUSTOMER_TRX_ID = B.CUSTOMER_TRX_ID(+)
AND A.SOLD_TO_CUSTOMER_ID = RA.CUSTOMER_ID
AND A.SOLD_TO_CUSTOMER_ID = E.CUSTOMER_ID
AND A.CREATED_BY = F.USER_ID
AND A.CUST_TRX_TYPE_ID = C.CUST_TRX_TYPE_ID
AND A.BATCH_SOURCE_ID = D.BATCH_SOURCE_ID
AND A.ORG_ID = '1344'
AND A.COMPLETE_FLAG = 'Y'
AND D.NAME = 'VALI AFT VENDA AUTOMATICA'
AND C.NAME NOT IN ('SI COMPL PRECO C/AR')
AND D.NAME NOT LIKE '%CANCELAMENTO%'
AND TRUNC(TRX_DATE) >= TO_DATE('&DATA_INIC', 'DD/MM/RRRR')
AND B.STATUS IS NULL
GROUP BY D.NAME --,A.INTERFACE_HEADER_ATTRIBUTE2  



UNION ALL



SELECT '2.RILA' "LOCAL",
       RIL.BATCH_SOURCE_NAME "SOURCE",
       COUNT(RIL.INTERFACE_LINE_ATTRIBUTE3) NF_DELIVERY,
       RIL.INTERFACE_LINE_ATTRIBUTE2 ORDEM,
       'Aguardar tempo de processamento RILA X SYNCHRO' "OBS"
  FROM APPS.XXRA_INTERFACE_LINES_BR_V RIL
WHERE RIL.ORG_ID = 1344
   AND TRUNC(RIL.CREATION_DATE) >= TO_DATE('&DATA_INIC', 'DD/MM/YY')
   AND RIL.BATCH_SOURCE_NAME IN
       ('VALI AFT VENDA AUTOMATICA', 'SHIPMENT INVOICES')
  AND RIL.WAREHOUSE_ID = 1627
   AND INTERFACE_LINE_ATTRIBUTE2 NOT LIKE '%EXP%'
GROUP BY RIL.BATCH_SOURCE_NAME, INTERFACE_LINE_ATTRIBUTE2



UNION ALL



SELECT '3.CANCELAR_NF' "LOCAL",
       D.NAME "SOURCE",
       COUNT(DISTINCT RCTLA.INTERFACE_LINE_ATTRIBUTE13) NF_DELIVERY,
       A.TRX_NUMBER || '_' || RA.CUSTOMER_NAME,
       'Critica das notas do cliente VESPOR que foram Faturadas com mais de um Pedido e devem ser canceladas.' "OBS"
  FROM APPS.XXRA_CUSTOMER_TRX_BR_V       A,
       APPS.XXCLL_F031_ELECTRONIC_TRX_ALL_BR_V  B,
       APPS.XXRA_CUST_TRX_TYPES_BR_V     C,
       APPS.XXRA_BATCH_SOURCES_BR_V      D,
       APPS.XXETN_RA_CUSTOMERS           E,
       APPS.FND_USER_VIEW                F,
       APPS.XXETN_RA_CUSTOMERS           RA,
       APPS.XXRA_CUSTOMER_TRX_LINES_BR_V RCTLA
WHERE A.CUSTOMER_TRX_ID = B.CUSTOMER_TRX_ID(+)
   AND A.CUSTOMER_TRX_ID = RCTLA.CUSTOMER_TRX_ID
   AND A.SOLD_TO_CUSTOMER_ID = RA.CUSTOMER_ID
   AND A.SOLD_TO_CUSTOMER_ID = E.CUSTOMER_ID
   AND A.CREATED_BY = F.USER_ID
   AND A.CUST_TRX_TYPE_ID = C.CUST_TRX_TYPE_ID
   AND A.BATCH_SOURCE_ID = D.BATCH_SOURCE_ID
   AND A.ORG_ID = '1344'
   AND A.COMPLETE_FLAG = 'Y'
   AND D.NAME = 'VALI AFT VENDA AUTOMATICA'
   AND C.NAME NOT IN ('SI COMPL PRECO C/AR')
   AND D.NAME NOT LIKE '%CANCELAMENTO%'
   AND RCTLA.LINE_TYPE = 'LINE'
   AND TRUNC(TRX_DATE) >= TO_DATE('&DATA_INIC', 'DD/MM/RRRR')
   AND RA.CUSTOMER_NAME = 'VESPOR AUTOMOTIVE DISTR DE AUTO PECAS LTDA'
GROUP BY A.TRX_NUMBER, D.NAME, RA.CUSTOMER_NAME
HAVING COUNT(DISTINCT RCTLA.INTERFACE_LINE_ATTRIBUTE13) > 1



UNION ALL



SELECT '4.RETORNO_SYNCHRO' "LOCAL",
       D.NAME "SOURCE",
       COUNT(D.NAME) NF_DELIVERY,
       A.TRX_NUMBER || '_HORARIO_' ||
       to_char(A.creation_DATE + .08333, 'HH24:MI:SS') hora_atual,
       'Critica as notas que não é possível imprimir as etiquetas. Fique atento ao horário, normalmente não deve passar de 30 minutos dependendo da quantidade de Notas Fiscais geradas.' "OBS"
  FROM APPS.XXRA_CUSTOMER_TRX_BR_V       A,
       --APPS.XXBS_EBI_ELECTRONIC_TRX_BR_V B,
       APPS.XXCLL_F031_ELECTRONIC_TRX_ALL_BR_V      B ,
       APPS.XXRA_CUST_TRX_TYPES_BR_V     C,
       APPS.XXRA_BATCH_SOURCES_BR_V      D,
       APPS.XXETN_RA_CUSTOMERS E,
       APPS.FND_USER_VIEW                F
WHERE A.CUSTOMER_TRX_ID = B.CUSTOMER_TRX_ID(+)
   AND A.SOLD_TO_CUSTOMER_ID = E.CUSTOMER_ID
   AND A.CREATED_BY = F.USER_ID
   AND A.CUST_TRX_TYPE_ID = C.CUST_TRX_TYPE_ID
   AND A.BATCH_SOURCE_ID = D.BATCH_SOURCE_ID
   AND A.ORG_ID = '1344'
   AND A.COMPLETE_FLAG = 'Y'
   AND D.NAME NOT LIKE '%CANCELAMENTO%'
   AND D.NAME = 'VALI AFT VENDA AUTOMATICA'
   AND TRUNC(TRX_DATE) >= TO_DATE('&DATA_INIC', 'DD/MM/RRRR')
   AND B.STATUS IS NULL
GROUP BY A.TRX_NUMBER, A.creation_DATE, D.NAME
ORDER BY 1, 2, 4
